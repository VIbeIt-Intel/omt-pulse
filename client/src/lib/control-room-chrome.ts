export type ControlRoomChrome = {
  [K in keyof (typeof copy)["en"]]: string;
};

export function controlRoomChrome(lang: ControlRoomLang): ControlRoomChrome {
  return copy[lang];
}

const NOTICE_AF: Array<[RegExp, string]> = [
  [/^Entered geofence:/, "Geofence binnegegaan:"],
  [/^Left geofence:/, "Geofence verlaat:"],
  [/^Left premises zone$/, "Perseelsone verlaat"],
  [/Entered monitored zone/g, "Gemonitorde sone binnegegaan"],
  [/Left monitored zone/g, "Gemonitorde sone verlaat"],
  [/ is outside the /g, " is buite "],
  [/ km radius/g, " km radius"],
];

export function translateNotice(lang: ControlRoomLang, text: string): string {
  if (lang !== "af" || !text) return text;
  return NOTICE_AF.reduce((line, [pattern, replacement]) => line.replace(pattern, replacement), text);
}

export function knownFieldLabel(lang: ControlRoomLang, label: string): string {
  if (lang !== "af") return label;
  const c = copy.af;
  const known: Record<string, string> = {
    "Incident Date": c.incidentDate,
    "Incident Time": c.incidentTime,
    Type: c.type,
    Location: c.location,
    Description: c.description,
  };
  return known[label] ?? label;
}
