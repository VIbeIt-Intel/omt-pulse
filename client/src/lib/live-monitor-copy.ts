export type LiveMonitorCopy = (typeof copy)["en"];

export function liveMonitorCopy(lang: ControlRoomLang): LiveMonitorCopy {
  return copy[lang];
}

export function monitorMapError(message: string | null, m: LiveMonitorCopy): string {
  if (!message) return m.mapsFailed;
  if (message.includes("not configured")) return m.mapsKeyMissing;
  if (message.includes("failed to load")) return m.mapsFailed;
  return message;
}
